"""SNS掲載用: 沖縄の事業者が対象外と読める制度を除く。

jGrants由来の制度は自治体独自の補助金でも target_area が「全国」になっていることがある
(2026-10-16: いわき市・京都市・東京港・北海道監督部の制度が「全国」扱いで投稿候補に入っていた)。
カルーセル表紙の「いま沖縄で募集中」と食い違うため、制度名・実施主体に
沖縄以外の都道府県名や市名が入っているものは投稿に使わない。
"""
import re

PREFS = ["北海道", "青森", "岩手", "宮城", "秋田", "山形", "福島", "茨城", "栃木", "群馬", "埼玉", "千葉",
         "東京", "神奈川", "新潟", "富山", "石川", "福井", "山梨", "長野", "岐阜", "静岡", "愛知", "三重",
         "滋賀", "京都", "大阪", "兵庫", "奈良", "和歌山", "鳥取", "島根", "岡山", "広島", "山口", "徳島",
         "香川", "愛媛", "高知", "福岡", "佐賀", "長崎", "熊本", "大分", "宮崎", "鹿児島"]
OKINAWA_CITIES = ["那覇", "宜野湾", "石垣", "浦添", "名護", "糸満", "沖縄", "豊見城", "うるま", "宮古島", "南城"]
CITY_RE = re.compile(r"([一-龥ぁ-んァ-ヶー]{1,5})市(?![場況民販街長政])")


def other_region(it):
    text = f"{it.get('name') or ''} {it.get('issuer') or ''}"
    if any(p in text for p in PREFS):
        return True
    for m in CITY_RE.finditer(text):
        if m.group(1).endswith("都"):  # 「都市」は一般名詞(京都市は都道府県名で判定済み)
            continue
        if not any(m.group(1).endswith(c) for c in OKINAWA_CITIES):
            return True
    return False
