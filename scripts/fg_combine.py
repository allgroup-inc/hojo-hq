def match_rule(name):
    """制度名に一致する最初のルールを返す(なければ None)。"""
    for keywords, ctype, note in RULES:
        if any(k in name for k in keywords):
            return {"type": ctype, "note": note}
    return None


def apply_default_combine(item):
    """combine 未設定のリスクグループ制度に既定の併給注意を付与する(シード側が常に優先)。"""
    if item.get("combine"):
        return item
    rule = match_rule(item.get("name", ""))
    if rule:
        item["combine"] = dict(rule)
    return item


def missing_combine_warnings(items):
    """リスクグループ該当なのに combine が無い制度の警告リスト(validate用の安全網)。"""
    warns = []
    for it in items:
        if not it.get("combine") and match_rule(it.get("name", "")):
            warns.append(f"{it.get('id')} ({it.get('name')}): 併給リスクグループ該当だが combine 未設定")
    return warns


if __name__ == "__main__":
    # self-test
    a = apply_default_combine({"name": "テスト町 こども医療費助成"})
    assert a["combine"]["type"] == "adjust" and "医療費" in a["combine"]["note"]
    b = apply_default_combine({"name": "テスト町 こども医療費助成", "combine": {"type": "stackable", "note": "個別"}})
    assert b["combine"]["note"] == "個別", "シード側のcombineが上書きされた"
    c = apply_default_combine({"name": "テスト町 観光振興補助"})
    assert "combine" not in c
    w = missing_combine_warnings([{"id": "x", "name": "テスト市 補聴器購入助成"}])
    assert len(w) == 1
    print("fg_combine self-test OK")
